import { test } from '@playwright/test'

test.use({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true })

const dir = process.env.SHOTS ?? 'test-results/gallery'

test('mobile gallery', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.goto('/#/c')
  await page.waitForTimeout(1200)
  await page.screenshot({ path: `${dir}/m01-home.png` })
  await page.goto('/#/c/request/r-nada')
  await page.waitForTimeout(800)
  await page.screenshot({ path: `${dir}/m02-request.png`, fullPage: true })
  await page.goto('/#/c/wallet')
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${dir}/m03-wallet-gate.png` })
  await page.getByRole('button', { name: 'ادخل برقم جوالك' }).click()
  await page.getByRole('button', { name: 'أرسل رمز التحقق' }).click({ timeout: 10_000 })
  await page.waitForTimeout(3000)
  await page.waitForTimeout(800)
  await page.screenshot({ path: `${dir}/m04-wallet.png` })
  await page.evaluate(() => document.getElementById('c-scroll')?.scrollTo(0, 2000))
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${dir}/m05-wallet-bottom.png` })
  await page.goto('/#/c/history')
  await page.waitForTimeout(800)
  await page.screenshot({ path: `${dir}/m06-history.png` })
  await page.goto('/#/c/me')
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${dir}/m07-me.png` })
  await page.goto('/#/l')
  await page.waitForTimeout(800)
  await page.screenshot({ path: `${dir}/m08-laundry.png`, fullPage: true })
  await page.goto('/#/l/new')
  await page.waitForTimeout(600)
  await page.screenshot({ path: `${dir}/m09-new.png` })
  await page.goto('/#/l/customer/u-demo')
  await page.waitForTimeout(600)
  await page.screenshot({ path: `${dir}/m10-customer-coupons.png` })
  await page.goto('/#/l/history')
  await page.waitForTimeout(600)
  await page.screenshot({ path: `${dir}/m11-laundry-history.png` })
  await page.goto('/#/f/certs')
  await page.waitForTimeout(600)
  await page.screenshot({ path: `${dir}/m12-certs.png` })
  await page.goto('/#/f')
  await page.waitForTimeout(900)
  await page.screenshot({ path: `${dir}/m13-factory.png` })
  await page.goto('/#/impact')
  await page.waitForTimeout(1200)
  await page.screenshot({ path: `${dir}/m14-impact.png`, fullPage: true })
  await page.goto('/#/c/scan')
  await page.waitForTimeout(4000)
  await page.screenshot({ path: `${dir}/m15-scan.png` })
})
