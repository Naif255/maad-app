import { expect, test, type Page } from '@playwright/test'

test.use({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true })

const dir = process.env.SHOTS ?? 'test-results/shots'

test('every screen at 390x844', async ({ page }) => {
  test.setTimeout(240_000)
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  const snap = async (name: string, wait = 700) => {
    await page.waitForTimeout(wait)
    await page.screenshot({ path: `${dir}/${name}.png` })
  }
  const scroll = async (id: string, y = 4000) => {
    await page.evaluate(([el, top]) => document.getElementById(el as string)?.scrollTo(0, top as number), [id, y])
    await page.waitForTimeout(400)
  }
  const go = async (path: string) => {
    await page.goto(path)
  }
  const welcome = async (p: Page) => {
    await p.goto('/#/welcome')
    await expect(p.getByText('مين أنت؟')).toBeVisible()
  }

  await page.goto('/')
  await page.evaluate(() => {
    localStorage.clear()
    sessionStorage.clear()
  })
  await page.goto('/')
  await expect(page.getByText('مين أنت؟')).toBeVisible()
  await snap('00-welcome', 2400)

  await page.getByRole('button', { name: /عندي علاقات/ }).click()
  await snap('01-consumer-phone', 500)
  await page.getByRole('button', { name: 'أرسل الرمز' }).click()
  await snap('02-consumer-otp', 1700)
  await expect(page.getByText('وين ساكن؟')).toBeVisible({ timeout: 6000 })
  await page.getByRole('button', { name: /الصفراء/ }).click()
  await snap('03-consumer-hood', 400)
  await page.getByRole('button', { name: 'يلا نبدأ' }).click()
  await expect(page.getByText('مغاسل قريبة تحتاج علاقات')).toBeVisible()
  await snap('04-home', 1000)
  await scroll('c-scroll')
  await snap('05-home-bottom', 200)
  await scroll('c-scroll', 0)
  await page.getByRole('button', { name: 'غيّر الحي' }).click()
  await snap('06-home-hood-sheet', 600)
  await page.mouse.click(195, 80)
  await go('/#/c/request/r-nada')
  await snap('07-request', 800)
  await go('/#/c/wallet')
  await snap('08-wallet', 1000)
  await scroll('c-scroll')
  await snap('09-wallet-bottom', 200)
  await go('/#/c/history')
  await snap('10-history', 800)
  await go('/#/c/me')
  await snap('11-me', 600)

  await welcome(page)
  await page.getByRole('button', { name: /عندي مغسلة/ }).click()
  await snap('20-laundry-signin', 500)
  await page.getByRole('button', { name: 'دخول' }).click()
  await expect(page.getByText('لوحة المغسلة')).toBeVisible()
  await snap('21-laundry-dashboard', 1000)
  await go('/#/l/history')
  await snap('22-laundry-receipts', 700)
  await page.getByRole('tab', { name: 'مدفوعات الخردة' }).click()
  await snap('23-laundry-payouts', 700)
  await go('/#/l/settings')
  await snap('24-laundry-settings', 600)
  await scroll('l-scroll')
  await snap('25-laundry-settings-bottom', 200)
  await go('/#/l/new')
  await snap('26-laundry-new', 700)

  await welcome(page)
  await page.getByRole('button', { name: /عندي مصنع/ }).click()
  await snap('30-factory-signin', 500)
  await page.getByRole('button', { name: 'دخول' }).click()
  await expect(page.getByText(/جاهز/).first()).toBeVisible()
  await snap('31-factory-boxes', 1200)
  await go('/#/f/round')
  await snap('32-factory-round-empty', 700)
  await go('/#/f/certs')
  await snap('33-factory-certs', 700)
  await page.getByRole('button').filter({ hasText: 'كجم' }).first().click()
  await snap('34-factory-cert', 1100)
  await go('/#/f/settings')
  await snap('35-factory-settings', 600)

  await go('/#/impact')
  await snap('40-impact', 1500)
  await scroll('impact-scroll', 900)
  await snap('41-impact-bottom', 600)

  await go('/?demo=1#/c/scan?for=r-nada')
  await snap('50-scan', 3500)
  await expect(page.getByText('تم التحقق').last()).toBeVisible({ timeout: 30_000 })
  await snap('51-scan-verified', 700)
  await expect(page.getByRole('button', { name: 'كمّل للفرز' })).toBeVisible({ timeout: 10_000 })
  await snap('52-scan-done', 700)
  const boxes = page.locator('button.absolute.left-0.top-0')
  for (let i = 0; i < (await boxes.count()); i++) {
    const b = await boxes.nth(i).boundingBox()
    if (b && b.y + b.height / 2 > 200 && b.y + b.height / 2 < 500) {
      await boxes.nth(i).click()
      break
    }
  }
  await snap('53-scan-criteria', 900)
  await page.mouse.click(195, 60)
  await page.waitForTimeout(500)
  await page.getByRole('button', { name: 'كمّل للفرز' }).click()
  await snap('54-summary', 900)
  await scroll('c-scroll')
  await snap('55-summary-bottom', 200)
  await page.getByRole('button', { name: 'احجز التسليم' }).click()
  await snap('56-method', 700)
  await page.getByRole('button', { name: 'ثبّت الحجز' }).click()
  await expect(page.getByText('رمزك الشخصي')).toBeVisible()
  await snap('57-receipt', 900)
  const code = (await page.getByTestId('booking-code').innerText()).trim()
  await scroll('c-scroll')
  await snap('58-receipt-bottom', 200)

  await go('/?demo=1#/l')
  await snap('60-laundry-pending', 900)
  await go('/?demo=1#/l/scan')
  await snap('61-laundry-scan', 1200)
  await page.getByRole('button', { name: new RegExp(code) }).click()
  await snap('62-laundry-customer', 800)
  await page.getByRole('button', { name: 'استلمت' }).click()
  await snap('63-laundry-received', 1600)
  await go('/?demo=1#/l')
  await snap('64-laundry-box-full', 1000)

  await go('/?demo=1#/c')
  await expect(page.getByText('وصلتك مكافأتك!')).toBeVisible()
  await snap('70-reward', 1600)
  await page.getByRole('button', { name: 'شوف بطاقة أثرك' }).click()
  await snap('71-impact-card', 1300)
  await go('/?demo=1#/c/history')
  await page.locator('#c-scroll button').first().click()
  await snap('72-history-detail', 900)

  await go('/?demo=1#/f')
  await snap('80-factory-ready', 1200)
  await scroll('f-scroll')
  await snap('81-factory-ready-bottom', 200)
  await page.getByRole('button', { name: 'جهّز جولة الاستلام' }).click()
  await snap('82-factory-round', 1300)
  await page.getByRole('button', { name: 'أكّد الوزن' }).click()
  await snap('83-factory-round-stop2', 900)
  await page.getByRole('button', { name: 'أكّد الوزن' }).click()
  await page.getByRole('button', { name: 'أكّد الوزن' }).click()
  await expect(page.getByText('صدرت شهادة التوريد')).toBeVisible()
  await scroll('f-scroll')
  await snap('84-factory-round-done', 800)
  await page.getByRole('button', { name: 'شوف الشهادة' }).click()
  await snap('85-factory-certificate', 1200)

  expect(errors).toEqual([])
})
